def anchor_round_robin_edges(anchors: dict | None,
                             prior_games: int = 2000) -> tuple[list, list[str]]:
    """The static bot-vs-bot round-robin as pairwise results, plus any caveats.

    ``data/gen3_bot_elo_anchors.json`` DOES store the raw matrix (a 9×9 ``win_matrix`` and a
    ``pair_games`` count per pair), so the real measured edges are used: ``n`` from
    ``pair_games`` and ``p`` from the two matrix halves averaged
    (``(p_ab + (1-p_ba))/2`` — they need not sum to 1, since unfinished battles are dropped
    from each side independently).

    FALLBACK, and it changes the meaning: if a future anchor file carries only ``ratings``,
    the bot edges are RECONSTRUCTED from those ratings as ``p = σ(ΔR)`` with a synthetic
    ``prior_games`` count. Reconstructed edges are transitive BY CONSTRUCTION — they carry
    zero residual and act purely as a high-confidence prior that pins the bot frame — so any
    width measured over a graph containing them is entirely the OTHER players' deviation.
    That is flagged in the returned caveats."""
    if not anchors or not anchors.get("ratings"):
        return [], ["no bot anchors — the bot frame is unpinned"]
    ratings = anchors["ratings"]
    matrix = anchors.get("win_matrix") or {}
    pair_games = anchors.get("pair_games") or {}
    out: list[tuple[str, str, int, int]] = []
    caveats: list[str] = []
    if matrix and pair_games:
        seen: set[tuple[str, str]] = set()
        for a, row in matrix.items():
            for b, p_ab in row.items():
                key = (a, b) if a < b else (b, a)
                if key in seen or a == b:
                    continue
                n = pair_games.get(f"{key[0]} vs {key[1]}")
                if n is None:
                    n = pair_games.get(f"{key[1]} vs {key[0]}")
                if not n:
                    continue
                seen.add(key)
                p_ba = (matrix.get(b) or {}).get(a)
                p = float(p_ab) if p_ba is None else 0.5 * (float(p_ab) + 1.0 - float(p_ba))
                p = min(max(p, 0.0), 1.0)
                if key[0] != a:
                    p = 1.0 - p
                out.append((elo_mod.bot_key(key[0]), elo_mod.bot_key(key[1]),
                            int(round(p * int(n))), int(n)))
        return out, caveats
    # Reconstruction fallback — see the docstring.
    caveats.append(f"anchor file has no win_matrix/pair_games; bot edges RECONSTRUCTED from "
                   f"anchor ratings at {prior_games} synthetic games — they are transitive by "
                   f"construction and act as a pinning prior, contributing no width of their own")
    bots = sorted(ratings)
    for i, a in enumerate(bots):
        for b in bots[i + 1:]:
            p = elo_mod.win_prob(float(ratings[a]), float(ratings[b]))
            out.append((elo_mod.bot_key(a), elo_mod.bot_key(b),
                        int(round(p * prior_games)), int(prior_games)))
    return out, caveats


def cycle_edges(step: int, bot_win_rates: dict, sentinels, n_games: int,
                bot_counts: dict | None = None,
                anchors: dict | None = None) -> tuple[list, str, list[str]]:
    """The LIVE graph for one eval cycle: the trainee's star **joined to the static bot
    round-robin**, which is the only thing that closes a triangle.

    A cycle's own new games are a STAR (trainee vs each opponent). A star is a tree; a tree
    has no cycles; so a width measured on the cycle's games alone would be identically zero —
    a fake instrument. The bot-vs-bot round-robin supplies the bot-side edges, and the
    trainee×bot×bot triangles they close are what the live width actually reads.

    Sentinel edges (trainee-vs-sentinel only) are INCLUDED in the fit — they carry real spine
    information — but they lie on no triangle, so the default width scope drops them. Their
    residual is identically zero anyway (a pendant edge's node equation is that one edge), so
    including them in a width claim would only deflate it.

    Returns ``(results, trainee_key, caveats)``."""
    subj = elo_mod.snap_key(int(step))
    results: list[tuple[str, str, int, int]] = []
    for name, wr in (bot_win_rates or {}).items():
        if bot_counts and name in bot_counts:
            won, fin = int(bot_counts[name][0]), int(bot_counts[name][1])
        else:
            fin = int(n_games)
            won = int(round(float(wr) * fin))
        if fin > 0:
            results.append((subj, elo_mod.bot_key(name), won, fin))
    for s in (sentinels or []):
        try:
            s_step, wr = int(s["step"]), float(s["win_rate"])
        except (KeyError, TypeError, ValueError):
            continue
        n = int(n_games)
        if n > 0:
            results.append((subj, elo_mod.snap_key(s_step), int(round(wr * n)), n))
    rr, caveats = anchor_round_robin_edges(anchors)
    results.extend(rr)
    return results, subj, caveats


def edges_from_run(run_dir: str, *, source: str = "auto", with_bot_rr: bool = False,
                   anchors_path: str = elo_mod.BOT_ANCHORS_PATH) -> tuple[list, list[str]]:
    """The OFFLINE graph for a run — exactly the edge set ``snapshot_ladder.fit_ladder``
    fits, so the width is measured over the same graph the ELO gate is read from:

    1. the DENSE frozen snapshot-vs-snapshot matrix (``snapshot_ladder/games.jsonl``), and
    2. every cycle's trainee-vs-bot and trainee-vs-sentinel edges (``eval_results.jsonl``).

    ``with_bot_rr`` additionally folds in the static bot-vs-bot round-robin. It is OFF by
    default and that is a judgment call worth stating: those 36 edges carry ~2700 games each
    against a ladder edge's 100, so on the Fisher weighting they would carry ~99% of Σw and
    the reported width would become a property of the (immutable, shared-across-runs) bot
    anchor rather than of this run's ladder. Turn it on to read the bots' own cycles."""
    results: list[tuple[str, str, int, int]] = []
    caveats: list[str] = []
    try:
        from agents.training import snapshot_ladder as ladder_mod
        for (lo, hi), (wins_lo, g) in ladder_mod.load_games(run_dir).items():
            if g > 0:
                results.append((elo_mod.snap_key(lo), elo_mod.snap_key(hi), wins_lo, g))
    except Exception as e:  # noqa: BLE001 — a run may have no dense ladder at all
        caveats.append(f"no dense frozen ladder ({type(e).__name__})")
    n_dense = len(results)
    if n_dense == 0:
        caveats.append("no snapshot_ladder/games.jsonl — the graph is the SPARSE live one "
                       "(trainee stars + sentinel edges); triangles exist only where a "
                       "sentinel edge coincides with a rated snapshot")
    for na, nb, wa, g in elo_mod._rows_to_results(elo_mod.load_rows(run_dir, source)):
        if g > 0:
            results.append((na, nb, wa, g))
    if with_bot_rr:
        rr, rr_cav = anchor_round_robin_edges(elo_mod.load_bot_anchors(anchors_path))
        results.extend(rr)
        caveats.extend(rr_cav)
        caveats.append("bot round-robin edges INCLUDED — they dominate Σw, so the width is "
                       "mostly the bot anchor's own non-transitivity")
    return results, caveats


def decompose_run(run_dir: str, *, source: str = "auto", with_bot_rr: bool = False,
                  anchors_path: str = elo_mod.BOT_ANCHORS_PATH,
                  bootstrap: int = DEFAULT_BOOTSTRAP, seed: int = 0,
                  max_cycles: int = MAX_CYCLES) -> "HodgeFit | None":
    """Convenience: build a run's ladder graph and decompose it. ``None`` when the run has no
    comparison graph yet."""
    results, caveats = edges_from_run(run_dir, source=source, with_bot_rr=with_bot_rr,
                                      anchors_path=anchors_path)
    fit = hodge_decompose(results, bootstrap=bootstrap, seed=seed, max_cycles=max_cycles)
    if fit is not None:
        fit.caveats = caveats + fit.caveats
    return fit


LIVE_BOOTSTRAP = 60

# The two live scalars. TWO, deliberately: a per-opponent series here would be per-opponent
# NOISE (one cycle's edge is ~100 games), and the per-opponent story is the offline read's job.
WIDTH_TAG = "eval/hodge_width_elo"
FRACTION_TAG = "eval/hodge_cyclic_fraction"


def live_read(step: int, bot_win_rates: dict, sentinels, n_games: int,
              bot_counts: dict | None = None,
              anchors_path: str = elo_mod.BOT_ANCHORS_PATH,
              bootstrap: int = LIVE_BOOTSTRAP, seed: int = 0) -> "HodgeFit | None":
    """The per-eval-cycle read: the trainee's matchup deviation from its own rating, measured
    over trainee×bot×bot triangles.

    ⚠️ This is the WEAK instrument by construction — one cycle's edges are ~100 games each,
    so the noise floor is large and only a gross cyclic profile clears it. The real width
    instrument is the offline dense-ladder read (``decompose_run`` / ``python -m main.elo``).
    Returns ``None`` when the graph has no testable triangle — the caller must then OMIT the
    metric (never record 0, never record NaN)."""
    anchors = elo_mod.load_bot_anchors(anchors_path)
    results, subj, caveats = cycle_edges(step, bot_win_rates, sentinels, n_games,
                                         bot_counts=bot_counts, anchors=anchors)
    fit = hodge_decompose(results, width_incident_to={subj}, bootstrap=bootstrap, seed=seed)
    if fit is None or fit.n_triangles == 0:
        return None
    fit.caveats = caveats + fit.caveats
    return fit


def record_live_hodge(logger, step: int, bot_win_rates: dict, sentinels, n_games: int, *,
                      bot_counts: dict | None = None,
                      anchors_path: str = elo_mod.BOT_ANCHORS_PATH,
                      bootstrap: int = LIVE_BOOTSTRAP, seed: int = 0) -> dict:
    """Record the two live scalars beside ``eval/elo`` and return the ``eval_results.jsonl``
    ``hodge`` block.

    * ``eval/hodge_width_elo`` — the EXCESS width (raw² − null², floored at 0) in ELO points:
      how far the trainee's matchup profile departs from what a single rating predicts, over
      and above what its own ~100-game edges could produce by chance.
    * ``eval/hodge_cyclic_fraction`` — the null-adjusted share of the trainee's flow energy
      that a rating cannot explain.

    **What it does NOT measure**: the width of the whole pool. This cycle's games are a STAR;
    the triangles come from joining them to the static bot round-robin, so the metric is
    "trainee×bot×bot" and nothing else. Sentinel edges enter the FIT (real spine information)
    but lie on no triangle and are excluded from the width scope.

    The block is ALWAYS returned (``recorded: false`` + a caveat when the graph has no
    testable triangle) so an offline reader can count the omissions; the scalars are recorded
    only when the number is real and finite — never 0-as-a-stand-in, never NaN. Best-effort:
    telemetry may not break eval."""
    try:
        fit = live_read(step, bot_win_rates, sentinels, n_games, bot_counts=bot_counts,
                        anchors_path=anchors_path, bootstrap=bootstrap, seed=seed)
    except Exception as e:  # noqa: BLE001 — telemetry; never break eval
        return {"recorded": False, "caveats": [f"hodge read failed: {type(e).__name__}: {e}"]}
    if fit is None:
        return {"recorded": False,
                "caveats": ["no testable triangle — the cycle's own games are a star, and no "
                            "bot round-robin edges were available to close one"]}
    width = fit.width_rms_excess_elo
    frac = fit.cyclic_energy_fraction_excess
    if not (math.isfinite(width) and math.isfinite(frac)):
        return {"recorded": False, "caveats": ["non-finite width — record omitted"]}
    if logger is not None:
        logger.record(WIDTH_TAG, float(width))
        logger.record(FRACTION_TAG, float(frac))
    return {
        "recorded": True,
        "width_elo": round(float(width), 2),
        "cyclic_fraction": round(float(frac), 4),
        "width_raw_elo": round(fit.width_rms_raw_elo, 2),
        "width_null_elo": round(fit.width_rms_null_elo, 2),
        "p_value": None if fit.p_value is None else round(fit.p_value, 4),
        "n_triangles": fit.n_triangles,
        "n_width_edges": fit.n_width_edges,
        "caveats": list(fit.caveats),
    }
