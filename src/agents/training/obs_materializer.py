_TAG_SEQ = 0


@dataclass(frozen=True)
class MaterializedDecision:
    """One decision point's full agent view: the observation the live policy
    would receive (obs-vector + prev-mask + turn-history, concatenated exactly
    as ``embed_battle`` returns it) and its action mask.

    ``obs`` is ``None`` for a TRACK-ONLY decision (one the caller asked NOT to encode via
    ``encode_only_at`` — the tracker is still advanced faithfully, only the expensive obs encode is
    skipped because nobody reads that decision's obs)."""

    obs: Optional[np.ndarray]
    mask: np.ndarray
    turn: int


@dataclass(frozen=True)
class MaterializedTrace:
    decisions: List[MaterializedDecision]
    # True when every materialized row had its action provided (full-history
    # faithfulness); False when the replay stopped one row past the last action.
    actions_complete: bool
    # When map_actions_at=i was requested: {action_idx: sim choice string} for
    # every LEGAL action at decision i, produced by the REAL action mapper
    # (Gen3ActionMapper via action_to_order) against the replayed battle state —
    # e.g. {6: "move icebeam", 2: "switch skarmory"}. None otherwise. This is
    # how a counterfactual consumer turns "alternative action index" into the
    # choice string reroll_turn needs, with zero mapping reimplementation.
    action_choices: Optional[dict] = None


class _ReplayObsPlayer(Gen3Player):
    """A transport-less Gen3Player that records ``embed_battle`` output at each
    decision instead of running a policy. Orders it returns go nowhere (the
    ``BattleStreamClient`` has no live bridge process registered)."""

    def __init__(self, *, replay_actions: Sequence[int],
                 map_actions_at: Optional[int] = None,
                 stop_after_decision: Optional[int] = None,
                 encode_only_at: "Optional[set]" = None, **kwargs):
        super().__init__(**kwargs)
        self._replay_actions = [int(a) for a in replay_actions]
        self._materialized: List[MaterializedDecision] = []
        self._actions_exhausted = False
        self._map_actions_at = map_actions_at
        self._stop_after = stop_after_decision
        # When set, ENCODE the obs only at these decision indices (others are track-only — the tracker
        # still advances faithfully, the encode is skipped). None = encode every decision (the default).
        self._encode_only_at = encode_only_at
        self._stopped = False
        self.action_choices: Optional[dict] = None

    @property
    def done(self) -> bool:
        return self._actions_exhausted or self._stopped

    def _encode_or_track(self, battle, i: int):
        """``(obs, mask)`` for decision ``i``, or ``None`` when this call is NOT a decision.

        Encode the obs only where the caller needs it (``encode_only_at``); elsewhere just TRACK
        (the tracker advances identically, the ~80%-cost encode is skipped → ``obs`` is None). The
        index ``i`` is this decision's position BEFORE the append (a no-decision ``mask.sum()==0``
        call doesn't append), so it lines up with the caller's ``encode_only_at`` indices.

        Shared with :class:`_InvertingReplayPlayer` so the two replay players cannot drift on the
        one step where drift would silently change an obs.
        """
        if self._encode_only_at is None or i in self._encode_only_at:
            obs_dict = self.embed_battle(battle)
            mask = obs_dict["action_mask"]
            if int(mask.sum()) == 0:
                return None
            return np.asarray(obs_dict["observation"], dtype=np.float32), mask
        _legal, mask, _tracker = self.track_decision(battle)
        if int(mask.sum()) == 0:
            return None
        return None, mask

    def choose_move(self, battle):
        # Mirror EvalRLPlayer.choose_move → RLPlayer._predict_best_action (see
        # module header). Order of operations is load-bearing.
        forfeit = self._handle_stall(battle, "REPLAY_STALL")
        if forfeit:
            return forfeit
        if self.done:
            return self.choose_default_move()
        i = len(self._materialized)
        step = self._encode_or_track(battle, i)
        if step is None:
            return self.choose_default_move()
        obs, mask = step
        self._materialized.append(
            MaterializedDecision(obs=obs, mask=np.asarray(mask), turn=battle.strict_view().turn))
        if i == self._map_actions_at:
            # Map every legal action through the REAL mapper at this exact
            # decision state — the choice strings a counterfactual re-roll
            # feeds back to the sim. Read-only (the mapper is pure).
            self.action_choices = {
                int(idx): self.action_to_order(int(idx), battle).message[len("/choose "):]
                for idx in np.flatnonzero(mask)
            }
        if i < len(self._replay_actions):
            self._get_tracker(battle).advance(self._replay_actions[i])
        else:
            # This row is still faithful (an obs depends on PRIOR actions only);
            # anything past it would fold an unknown action into the history.
            self._actions_exhausted = True
        if self._stop_after is not None and i >= self._stop_after:
            self._stopped = True
        return self.choose_default_move()


def materialize_decisions(
    chunks: Sequence[str],
    *,
    username: str,
    packed_team: str,
    side: str,
    actions: Sequence[int] = (),
    battle_format: str = "gen3ou",
    battle_tag: Optional[str] = None,
    mappings=None,
    stall_config: Optional[StallConfig] = None,
    map_actions_at: Optional[int] = None,
    stop_after_decision: Optional[int] = None,
    encode_only_at: "Optional[set]" = None,
) -> MaterializedTrace:
    """Replay one side's protocol ``chunks`` through the real obs pipeline.

    ``chunks`` are that side's chunks from :func:`utils.bridge.reconstruction.replay_battle`
    (or ``prefix + reroll`` chunks from :func:`...reroll_turn`). ``username`` /
    ``packed_team`` / ``side`` describe the side being replayed — take them from
    the record (``record.username(side)`` / ``record.packed_team(side)``); the
    username must match so poke-env resolves the player's role. ``actions`` are
    the live action indices (``states.npz["actions"]``) consumed one per
    materialized decision.

    ``map_actions_at=i`` additionally returns, in ``.action_choices``, the
    legal action-index → sim-choice-string mapping at decision ``i`` (via the
    real action mapper) — what a counterfactual consumer feeds ``reroll_turn``.
    ``stop_after_decision=i`` stops the replay once row ``i`` is materialized
    (cheap when only a prefix is needed).

    ``encode_only_at`` (a set of decision indices) ENCODES the obs only at those decisions; the rest
    are TRACK-ONLY (``decision.obs is None``) — the tracker still advances faithfully, but the
    expensive obs encode (~80% of the per-decision cost) is skipped where the caller won't read it
    (e.g. a search that needs only ONE successor's obs, or a choice-map / action-history pass that
    needs none). ``None`` (default) encodes every decision. The encoded decisions' obs are bit-for-bit
    identical to a full encode (the skipped encode is read-only on the tracker).
    """
    tag = _next_tag(battle_tag, battle_format)
    player, client = _build_replay_player(
        username=username, packed_team=packed_team, side=side, actions=actions,
        battle_format=battle_format, mappings=mappings, stall_config=stall_config,
        map_actions_at=map_actions_at, stop_after_decision=stop_after_decision,
        encode_only_at=encode_only_at,
    )
    _refuse_poke_loop("materialize_decisions")
    asyncio.run_coroutine_threadsafe(_feed(client, player, chunks, tag, first=True),
                                     POKE_LOOP).result()
    return MaterializedTrace(
        decisions=list(player._materialized),
        actions_complete=not player._actions_exhausted,
        action_choices=player.action_choices,
    )


def _next_tag(battle_tag: Optional[str], battle_format: str) -> str:
    global _TAG_SEQ
    _TAG_SEQ += 1
    return battle_tag or f"battle-{battle_format}-recon{_TAG_SEQ}"


def _build_replay_player(*, username: str, packed_team: str, side: str,
                         actions: Sequence[int], battle_format: str, mappings,
                         stall_config, map_actions_at, stop_after_decision, encode_only_at):
    """The player + transport-less client every replay path uses. Split out so the
    single-shot and prefix-sharing entry points build IDENTICAL objects (any drift here
    would silently break the bit-identity contract between them)."""
    player = _ReplayObsPlayer(
        replay_actions=actions,
        map_actions_at=map_actions_at,
        stop_after_decision=stop_after_decision,
        encode_only_at=encode_only_at,
        mappings=mappings,
        stall_config=stall_config,
        battle_format=battle_format,
        account_configuration=AccountConfiguration(username, None),
        server_configuration=LocalhostServerConfiguration,
        start_listening=False,
        max_concurrent_battles=1,
    )
    client = BattleStreamClient(
        player.ps_client._account_configuration,
        side=side,
        on_battle_message=player._handle_battle_message,
        on_update_challenges=player._update_challenges,
        on_challenge_request=player._handle_challenge_request,
        loop=POKE_LOOP,
    )
    player.ps_client = client
    # What _create_battle reads for the declared-team tracking (live: set by
    # get_next_team() just before the battle starts).
    player._current_packed_team = packed_team
    return player, client


async def _feed(client, player, chunks: Sequence[str], tag: str, *, first: bool) -> int:
    """Feed ``chunks`` and return how many were CONSUMED (the loop stops early once the
    player is done). The count is what lets :func:`materialize_branches` hand the
    still-unfed tail of a prefix to each branch instead of silently dropping it."""
    inited = not first
    consumed = 0
    for chunk in chunks:
        header = f">{tag}\n"
        if not inited:
            inited = True
            header += "|init|battle\n"
        # Awaited fully per chunk — the exact sequential-deterministic
        # delivery the eval bridge path (`run_local_battles._demux`) uses.
        await client.feed(header + chunk)
        consumed += 1
        if player.done:
            break
    return consumed


def _refuse_poke_loop(who: str) -> None:
    """The player's asyncio primitives live on POKE_LOOP (poke-env's background loop
    thread), so the feed must run there. ``run_coroutine_threadsafe`` works from sync
    context AND from inside any OTHER running loop; only a caller already on POKE_LOOP
    itself would deadlock on ``.result()`` — refuse loudly."""
    try:
        if asyncio.get_running_loop() is POKE_LOOP:
            raise RuntimeError(f"{who} must not be called from POKE_LOOP")
    except RuntimeError as e:
        if "POKE_LOOP" in str(e):
            raise


