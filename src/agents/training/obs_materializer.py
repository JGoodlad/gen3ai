"""Materialize the agent's ONE-SIDED observations from a battle's replayed protocol.

The forensic ``states.npz`` saves the obs vectors of states that *happened*; it
cannot score a counterfactual (a re-rolled turn), and the encoder's stateful
trackers (HiddenPowerTracker, ability/usage narrowing, the turn-history deltas,
the progress clock) are not recoverable from the 3457-dim output vector. The way
to get the obs of ANY point — recorded or re-rolled — is to replay the one-sided
protocol stream through the *real* obs pipeline from battle start, rebuilding
the tracker state exactly as the live player did. That replay is what this
module does.

**The one-sided / omniscient wall (hard requirement).** Input here is only the
per-side protocol chunks regenerated by ``utils.bridge.reconstruction``
(:func:`replay_battle` / :func:`reroll_turn`) — the exact bytes the live agent
saw. The omniscient reconstruction data (seed, both teams, dice) never enters
this module; the encoder reads the same partial poke-env view it reads live.

Fidelity contract
-----------------
``_ReplayObsPlayer`` mirrors the live eval decision cadence
(``EvalRLPlayer.choose_move`` → ``RLPlayer._predict_best_action``) exactly:

1. stall check first (same default :class:`StallConfig`, threshold 250 — the
   forfeit order goes nowhere, the recorded FORCELOSE in the replayed protocol
   ends the battle identically);
2. ``embed_battle`` (which records the decision context, updates the
   HiddenPowerTracker and the progress clock, and encodes the obs);
3. an all-zero mask ⇒ no decision (no row, no tracker advance) — the live
   ``idx is None`` deferral;
4. otherwise one materialized row, then ``tracker.advance(action)`` with the
   action the live player ACTUALLY took (``states.npz["actions"]``) — the chosen
   action feeds the turn-history fold, so replaying it is required for
   bit-faithful subsequent obs.

The round-trip guarantee (replaying a recorded battle reproduces the saved
``states.npz`` obs bit-for-bit) is enforced by
``agents/training/obs_roundtrip_fuzz_test.py``.

Counterfactual use (Phase 1)
----------------------------
Materializing a re-rolled continuation is composition, not new machinery: feed
``prefix_chunks + reroll.pN_chunks`` with the recorded actions for the prefix.
Rows are appended only while their history is faithful — one row past the last
provided action is still valid (an obs depends on *prior* actions only), which
is exactly the V(s′) row a re-roll consumer needs; after that the replay stops.

Prefix sharing (many branches of ONE decision)
----------------------------------------------
K counterfactual arms of the same decision share an identical prefix, and
replaying it K times is the measured bottleneck of the counterfactual label path
(``arm_ms = 4.78 + 0.853·turn``, of which prefix replay is ``2.53 + 0.855·turn``;
the branched turn itself is ~0.5 ms and the obs encode ~1.8 ms — cost model
2026-08-21). :func:`materialize_branches` replays the prefix **once**, snapshots
the player's whole battle/tracker state at the branch decision, and restores that
snapshot per arm. It is defined to be *exactly* equivalent to calling
:func:`materialize_decisions` once per arm on ``prefix + suffix`` — bit-for-bit
on every obs — and that equivalence is what
``obs_materializer_branch_integration_test.py`` pins. Measured on 6 gen-17
eval battles / 59 decisions / 452 arms: **59/59 byte-identical, 15.4 → 5.3 ms per
arm (2.91×)**, rising with the branch turn (3.7–3.9× at turn 26–28) because the
prefix cost it removes is the part that is linear in the turn.

Known limit: a battle containing a true ``[Invalid choice]`` error round cannot
be mirrored exactly (poke-env answers those with a coin-flip default); the
server-authoritative mask makes them no-ops in practice. The
``[Unavailable choice]`` maybe-trapped probe IS reproduced exactly — the raw
command log replays the refused attempt, regenerating the same |error| line,
rejection event, and re-request the live player saw.
"""

