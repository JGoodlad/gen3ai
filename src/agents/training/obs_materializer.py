_TAG_SEQ = 0


@dataclass(frozen=True)
class MaterializedDecision:
    """One decision point's full agent view: the observation the live policy
    would receive (obs-vector + prev-mask + turn-history, concatenated exactly
    as ``embed_battle`` returns it) and its action mask.

    ``obs`` is ``None`` for a TRACK-ONLY decision (one the caller asked NOT to encode via
    ``encode_only_at`` — the tracker is still advanced faithfully, only the expensive obs encode is
    skipped because nobody reads that decision's obs)."""

    obs: Optional[np.ndarray]
    mask: np.ndarray
    turn: int


@dataclass(frozen=True)
class MaterializedTrace:
    decisions: List[MaterializedDecision]
    # True when every materialized row had its action provided (full-history
    # faithfulness); False when the replay stopped one row past the last action.
    actions_complete: bool
    # When map_actions_at=i was requested: {action_idx: sim choice string} for
    # every LEGAL action at decision i, produced by the REAL action mapper
    # (Gen3ActionMapper via action_to_order) against the replayed battle state —
    # e.g. {6: "move icebeam", 2: "switch skarmory"}. None otherwise. This is
    # how a counterfactual consumer turns "alternative action index" into the
    # choice string reroll_turn needs, with zero mapping reimplementation.
    action_choices: Optional[dict] = None


class _ReplayObsPlayer(Gen3Player):
    """A transport-less Gen3Player that records ``embed_battle`` output at each
    decision instead of running a policy. Orders it returns go nowhere (the
    ``BattleStreamClient`` has no live bridge process registered)."""

    def __init__(self, *, replay_actions: Sequence[int],
                 map_actions_at: Optional[int] = None,
                 stop_after_decision: Optional[int] = None,
                 encode_only_at: "Optional[set]" = None, **kwargs):
        super().__init__(**kwargs)
        self._replay_actions = [int(a) for a in replay_actions]
        self._materialized: List[MaterializedDecision] = []
        self._actions_exhausted = False
        self._map_actions_at = map_actions_at
        self._stop_after = stop_after_decision
        # When set, ENCODE the obs only at these decision indices (others are track-only — the tracker
        # still advances faithfully, the encode is skipped). None = encode every decision (the default).
        self._encode_only_at = encode_only_at
        self._stopped = False
        self.action_choices: Optional[dict] = None

    @property
    def done(self) -> bool:
        return self._actions_exhausted or self._stopped

    def _choice_map(self, battle, mask) -> dict:
        """``{legal action index: sim choice string}`` at THIS decision, via the REAL mapper.

        The one definition, shared by ``map_actions_at`` (one decision, for a counterfactual
        re-roll) and by :class:`_InvertingReplayPlayer`'s ``capture_choices`` (every decision, for
        `cf_q_labels`' per-action sweep) — two callers that must never disagree about what "the
        choice string for action a" is, since one of them feeds the sim and the other feeds a
        label.

        Read-only: the mapper is pure. A candidate that RAISES is skipped rather than propagated,
        the same tolerance :meth:`_InvertingReplayPlayer._invert` has always applied — a stale or
        unmappable index is not a legal alternative, and a consumer that needs a specific index
        checks for its presence (`falsifier.falsify_decision` does exactly that).
        """
        out = {}
        for idx in np.flatnonzero(np.asarray(mask)):
            try:
                out[int(idx)] = self.action_to_order(
                    int(idx), battle).message[len("/choose "):]
            except Exception:  # noqa: BLE001 — an unmappable candidate is not an alternative
                continue
        return out

    def _encode_or_track(self, battle, i: int):
        """``(obs, mask)`` for decision ``i``, or ``None`` when this call is NOT a decision.

        Encode the obs only where the caller needs it (``encode_only_at``); elsewhere just TRACK
        (the tracker advances identically, the ~80%-cost encode is skipped → ``obs`` is None). The
        index ``i`` is this decision's position BEFORE the append (a no-decision ``mask.sum()==0``
        call doesn't append), so it lines up with the caller's ``encode_only_at`` indices.

        Shared with :class:`_InvertingReplayPlayer` so the two replay players cannot drift on the
        one step where drift would silently change an obs.
        """
        if self._encode_only_at is None or i in self._encode_only_at:
            obs_dict = self.embed_battle(battle)
            mask = obs_dict["action_mask"]
            if int(mask.sum()) == 0:
                return None
            return np.asarray(obs_dict["observation"], dtype=np.float32), mask
        _legal, mask, _tracker = self.track_decision(battle)
        if int(mask.sum()) == 0:
            return None
        return None, mask

    def choose_move(self, battle):
        # Mirror EvalRLPlayer.choose_move → RLPlayer._predict_best_action (see
        # module header). Order of operations is load-bearing.
        forfeit = self._handle_stall(battle, "REPLAY_STALL")
        if forfeit:
            return forfeit
        if self.done:
            return self.choose_default_move()
        i = len(self._materialized)
        step = self._encode_or_track(battle, i)
        if step is None:
            return self.choose_default_move()
        obs, mask = step
        self._materialized.append(
            MaterializedDecision(obs=obs, mask=np.asarray(mask), turn=battle.strict_view().turn))
        if i == self._map_actions_at:
            # Map every legal action through the REAL mapper at this exact
            # decision state — the choice strings a counterfactual re-roll
            # feeds back to the sim. Read-only (the mapper is pure).
            self.action_choices = self._choice_map(battle, mask)
        if i < len(self._replay_actions):
            self._get_tracker(battle).advance(self._replay_actions[i])
        else:
            # This row is still faithful (an obs depends on PRIOR actions only);
            # anything past it would fold an unknown action into the history.
            self._actions_exhausted = True
        if self._stop_after is not None and i >= self._stop_after:
            self._stopped = True
        return self.choose_default_move()


def materialize_decisions(
    chunks: Sequence[str],
    *,
    username: str,
    packed_team: str,
    side: str,
    actions: Sequence[int] = (),
    battle_format: str = "gen3ou",
    battle_tag: Optional[str] = None,
    mappings=None,
    stall_config: Optional[StallConfig] = None,
    map_actions_at: Optional[int] = None,
    stop_after_decision: Optional[int] = None,
    encode_only_at: "Optional[set]" = None,
) -> MaterializedTrace:
    """Replay one side's protocol ``chunks`` through the real obs pipeline.

    ``chunks`` are that side's chunks from :func:`utils.bridge.reconstruction.replay_battle`
    (or ``prefix + reroll`` chunks from :func:`...reroll_turn`). ``username`` /
    ``packed_team`` / ``side`` describe the side being replayed — take them from
    the record (``record.username(side)`` / ``record.packed_team(side)``); the
    username must match so poke-env resolves the player's role. ``actions`` are
    the live action indices (``states.npz["actions"]``) consumed one per
    materialized decision.

    ``map_actions_at=i`` additionally returns, in ``.action_choices``, the
    legal action-index → sim-choice-string mapping at decision ``i`` (via the
    real action mapper) — what a counterfactual consumer feeds ``reroll_turn``.
    ``stop_after_decision=i`` stops the replay once row ``i`` is materialized
    (cheap when only a prefix is needed).

    ``encode_only_at`` (a set of decision indices) ENCODES the obs only at those decisions; the rest
    are TRACK-ONLY (``decision.obs is None``) — the tracker still advances faithfully, but the
    expensive obs encode (~80% of the per-decision cost) is skipped where the caller won't read it
    (e.g. a search that needs only ONE successor's obs, or a choice-map / action-history pass that
    needs none). ``None`` (default) encodes every decision. The encoded decisions' obs are bit-for-bit
    identical to a full encode (the skipped encode is read-only on the tracker).
    """
    tag = _next_tag(battle_tag, battle_format)
    player, client = _build_replay_player(
        username=username, packed_team=packed_team, side=side, actions=actions,
        battle_format=battle_format, mappings=mappings, stall_config=stall_config,
        map_actions_at=map_actions_at, stop_after_decision=stop_after_decision,
        encode_only_at=encode_only_at,
    )
    _refuse_poke_loop("materialize_decisions")
    asyncio.run_coroutine_threadsafe(_feed(client, player, chunks, tag, first=True),
                                     POKE_LOOP).result()
    return MaterializedTrace(
        decisions=list(player._materialized),
        actions_complete=not player._actions_exhausted,
        action_choices=player.action_choices,
    )


def _next_tag(battle_tag: Optional[str], battle_format: str) -> str:
    """A tag for an OFFLINE replay battle — always UNIQUE, never the caller's verbatim.

    🚨 **THE UNIQUENESS IS A CORRECTNESS PROPERTY, NOT TIDINESS** (`gen3_recon_tag_collision_v1`,
    found 2026-09-19). A caller passing ``battle_tag=record.battle_tag`` used to get that tag back
    unchanged, so an offline replay of a LIVE battle ran in the SAME ROOM as the live battle it
    was replaying. The search-dividend live recorder's choice tap
    (``main.search_dividend.record.install_choice_tap``) is a process-wide patch on
    ``BattleStreamClient._write_choice`` whose ONLY discriminator is that room — so every
    ``/choose default`` the replay player emits when its action list runs out was appended to the
    LIVE reconstruction record as if the live player had chosen it.

    **What that cost, measured on the `playoff` arm:** the record collected ~1 spurious ``default``
    per materialized ARM (8.6 arms/decision on the repro cell), so by turn 2 the trainee's script
    read ``[default x10, 'switch Tyranitar']``. Every nested rollout then replayed a prefix that
    was not the battle, and **64 of 66 playoffs were lost** to
    ``unresolvable choice for pN: MoveName(...)`` — the substituted token naming a BENCHED mon,
    which is the shape of a prefix that has arrived somewhere else.

    ⚠️ **AND IT WAS NEVER A RUST DEFECT.** The ten spurious ``default``s appear byte-for-byte under
    ``--impl node`` too; node's bridge RE-REQUESTS on an unresolvable choice where rust fails loud
    (its own error says "Re-requesting would loop forever, so this fails loud"), so the node cell
    ran every rollout down a line nobody asked for and reported a clean number. The loud impl was
    the one telling the truth.

    The caller's tag is KEPT as a prefix so a replay is still traceable to the battle it replays,
    and the format stays in segment 1 because ``Player._create_battle`` checks exactly that.

    🚨 **A caller's tag WITHOUT the format in segment 1 is PREFIXED, never passed through.** A
    Rust-eval core trace's ``battle_tag`` is its ``battle_id`` (``core-<step>-<opp>-g<k>``), and a
    room named that is silently NOT a battle to ``Player._create_battle`` — the replay then yields
    ZERO decisions and every counterfactual view read "replay desync" (found 2026-09-30, M5 Lane H).
    """
    global _TAG_SEQ
    _TAG_SEQ += 1
    base = battle_tag or f"battle-{battle_format}"
    if base.split("-")[1:2] != [battle_format]:
        base = f"battle-{battle_format}-{base}"
    return f"{base}-recon{_TAG_SEQ}"


def _build_replay_player(*, username: str, packed_team: str, side: str,
                         actions: Sequence[int], battle_format: str, mappings,
                         stall_config, map_actions_at, stop_after_decision, encode_only_at,
                         player_cls: "Optional[type]" = None):
    """The player + transport-less client every replay path uses. Split out so the
    single-shot and prefix-sharing entry points build IDENTICAL objects (any drift here
    would silently break the bit-identity contract between them). ``player_cls`` (a
    :class:`_ReplayObsPlayer` subclass) lets a reader that records at each decision — the
    prober's core-trace expansion — reuse this exact construction."""
    player = (player_cls or _ReplayObsPlayer)(
        replay_actions=actions,
        map_actions_at=map_actions_at,
        stop_after_decision=stop_after_decision,
        encode_only_at=encode_only_at,
        mappings=mappings,
        stall_config=stall_config,
        battle_format=battle_format,
        account_configuration=AccountConfiguration(username, None),
        server_configuration=LocalhostServerConfiguration,
        start_listening=False,
        max_concurrent_battles=1,
    )
    client = BattleStreamClient(
        player.ps_client._account_configuration,
        side=side,
        on_battle_message=player._handle_battle_message,
        on_update_challenges=player._update_challenges,
        on_challenge_request=player._handle_challenge_request,
        loop=POKE_LOOP,
    )
    player.ps_client = client
    # What _create_battle reads for the declared-team tracking (live: set by
    # get_next_team() just before the battle starts).
    player._current_packed_team = packed_team
    return player, client


async def _feed(client, player, chunks: Sequence[str], tag: str, *, first: bool) -> int:
    """Feed ``chunks`` and return how many were CONSUMED (the loop stops early once the
    player is done). (The count served the deleted ``materialize_branches``, which handed the
    still-unfed tail of a prefix to each branch — P6 slice 5.)"""
    inited = not first
    consumed = 0
    for chunk in chunks:
        header = f">{tag}\n"
        if not inited:
            inited = True
            header += "|init|battle\n"
        # Awaited fully per chunk — the exact sequential-deterministic
        # delivery the eval bridge path (`run_local_battles._demux`) uses.
        await client.feed(header + chunk)
        consumed += 1
        if player.done:
            break
    return consumed


def _refuse_poke_loop(who: str) -> None:
    """The player's asyncio primitives live on POKE_LOOP (poke-env's background loop
    thread), so the feed must run there. ``run_coroutine_threadsafe`` works from sync
    context AND from inside any OTHER running loop; only a caller already on POKE_LOOP
    itself would deadlock on ``.result()`` — refuse loudly."""
    try:
        if asyncio.get_running_loop() is POKE_LOOP:
            raise RuntimeError(f"{who} must not be called from POKE_LOOP")
    except RuntimeError as e:
        if "POKE_LOOP" in str(e):
            raise


class _InvertingReplayPlayer(_ReplayObsPlayer):
    """Like :class:`_ReplayObsPlayer`, but instead of consuming a provided action-index list it
    RECOVERS each decision's action index by inverting the side's recorded sim-choice string through
    the real mapper. Two callers: the OPPONENT's action-index history for an interior search ply
    (the trace records only the trainee's actions), and :func:`scan_record`'s read of a TRAINING
    record, which has no recorded actions for either side."""

    def __init__(self, *, recorded_choices: Sequence[str],
                 capture_choices: bool = False, **kwargs):
        super().__init__(replay_actions=(), **kwargs)
        self._queue = list(recorded_choices)
        # `gen3_cf_q_labels_v1`: capture the FULL legal action → choice-string map at EVERY
        # decision, not just one. `map_actions_at` answers that question for a single decision and
        # costs a whole prefix replay per question; the per-action label sweep asks it for every
        # decision it might label, and this replay is already visiting all of them. OFF by default
        # — it is ~n_legal extra pure mapper calls per decision and nobody else wants them.
        self._capture_choices = bool(capture_choices)
        self.decision_choices: List[dict] = []
        self.inverted_actions: List[int] = []
        # The recorded sim-choice STRING that was accepted at each decision — the same list
        # `inverted_actions` holds the index form of. A counterfactual that wants to replay "the
        # action that was actually taken" needs the string (that is what the sim eats), and
        # re-deriving it from the index would be a second mapping implementation.
        self.accepted_choices: List[str] = []

    def choose_move(self, battle):
        forfeit = self._handle_stall(battle, "REPLAY_STALL")
        if forfeit:
            return forfeit
        if self._stopped:
            return self.choose_default_move()
        # Inversion needs only the MASK (to map choices via the real mapper); the obs is encoded only
        # where the caller asked for it (`encode_only_at`; `infer_action_indices` asks nowhere, so it
        # stays TRACK-ONLY throughout and skips the ~80%-cost encode at every decision).
        i = len(self._materialized)
        step = self._encode_or_track(battle, i)
        if step is None:
            return self.choose_default_move()
        obs, mask = step
        self._materialized.append(MaterializedDecision(
            obs=obs, mask=np.asarray(mask), turn=battle.strict_view().turn))
        if self._capture_choices:
            # BEFORE the tracker advances, like `map_actions_at` — the mapper reads the battle as
            # it stands at the decision, which is the state the choice strings must be legal in.
            #
            # `_invert` below maps the same indices again rather than reading this dict, and the
            # duplication is deliberate: it leaves the map and the recovered action index two
            # INDEPENDENT computations, so `choices[action] == choice` is a real cross-check
            # (`cf_producer_integration_test` asserts exactly that) instead of a tautology. The
            # cost is ~n_legal pure mapper calls on a path measured at ~0.3% of the producer's
            # wall, against a wrong map being a silently MISLABELLED action.
            self.decision_choices.append(self._choice_map(battle, mask))
        # Pop recorded choices until one INVERTS to a legal index (a refused maybe-trapped probe
        # inverts to None — consume it and try the correction, mirroring the sim's queue semantics).
        idx, accepted = None, None
        while self._queue and idx is None:
            accepted = self._queue.pop(0)
            idx = self._invert(battle, accepted, mask)
        if idx is not None:
            self.inverted_actions.append(int(idx))
            self.accepted_choices.append(str(accepted))
            self._get_tracker(battle).advance(int(idx))
        else:
            self._actions_exhausted = True
        if self._stop_after is not None and i >= self._stop_after:
            self._stopped = True
        return self.choose_default_move()

    def _invert(self, battle, choice_str: str, mask) -> Optional[int]:
        for idx in np.flatnonzero(np.asarray(mask)):
            try:
                order = self.action_to_order(int(idx), battle)
            except Exception:  # noqa: BLE001 — a stale/illegal candidate is just not a match
                continue
            if order.message[len("/choose "):] == choice_str:
                return int(idx)
        return None


def _run_inverting_replay(
    record: ReconstructionRecord,
    side: str,
    *,
    who: str,
    mappings=None,
    stall_config: Optional[StallConfig] = None,
    stop_after_decision: Optional[int] = None,
    chunks: "Optional[Sequence[str]]" = None,
    impl: str = "node",
    encode: bool = False,
    capture_choices: bool = False,
) -> "_InvertingReplayPlayer":
    """Replay ``side``'s recorded battle through an :class:`_InvertingReplayPlayer` and return it.

    Shared by :func:`infer_action_indices` (``encode=False`` — indices only) and
    :func:`scan_record` (``encode=True`` — indices, choice strings AND the one-sided obs). One
    function so the two cannot drift on the replay setup, which is the part that would silently
    change an obs rather than fail.
    """
    global _TAG_SEQ
    _TAG_SEQ += 1
    name = record.username(side)
    if chunks is None:
        rep = replay_battle(record, impl=impl)
        chunks = rep.p1_chunks if side == "p1" else rep.p2_chunks
    recorded = [c for (s, c) in record.commands if s == side]
    player = _InvertingReplayPlayer(
        recorded_choices=recorded, stop_after_decision=stop_after_decision, mappings=mappings,
        capture_choices=capture_choices,
        # `None` encodes EVERY decision, the empty set encodes NONE — the two callers' two modes.
        encode_only_at=None if encode else set(),
        stall_config=stall_config,
        battle_format=record.format_id,
        account_configuration=AccountConfiguration(name, None),
        server_configuration=LocalhostServerConfiguration,
        start_listening=False, max_concurrent_battles=1)
    client = BattleStreamClient(
        player.ps_client._account_configuration, side=side,
        on_battle_message=player._handle_battle_message,
        on_update_challenges=player._update_challenges,
        on_challenge_request=player._handle_challenge_request, loop=POKE_LOOP)
    player.ps_client = client
    player._current_packed_team = record.packed_team(side)
    tag = record.battle_tag or f"battle-{record.format_id}-recon{_TAG_SEQ}"

    async def _feed_all() -> None:
        inited = False
        for chunk in chunks:
            header = f">{tag}\n"
            if not inited:
                inited = True
                header += "|init|battle\n"
            await client.feed(header + chunk)
            if player.done:
                break

    _refuse_poke_loop(who)
    asyncio.run_coroutine_threadsafe(_feed_all(), POKE_LOOP).result()
    # Every materialized decision must have inverted to exactly one action index. A shortfall means a
    # recorded choice failed to invert (an [Invalid choice] round, or a mapper edge) — which would
    # silently DESYNC the obs (its action history would be a ply short). Fail LOUD instead.
    if len(player.inverted_actions) != len(player._materialized):
        raise RuntimeError(
            f"{who}({side}): recovered {len(player.inverted_actions)} action indices for "
            f"{len(player._materialized)} decisions — a recorded choice failed to invert, so the "
            f"action history would desync the obs. This battle can't drive a faithful "
            f"replay of this side.")
    return player


def infer_action_indices(
    record: ReconstructionRecord,
    side: str,
    *,
    mappings=None,
    stop_after_decision: Optional[int] = None,
    chunks: "Optional[Sequence[str]]" = None,
    impl: str = "node",
) -> "list[int]":
    """Recover ``side``'s ACTION-INDEX history by replaying its recorded battle and inverting each
    recorded sim-choice string through the real mapper. The counterpart of ``states.npz['actions']``
    for the OPPONENT (the forensic trace records only the trainee's actions), so the opponent's
    one-sided obs can be materialized faithfully for an interior search ply. Refused maybe-trapped
    probes invert to ``None`` and are skipped (queue semantics).

    ``chunks`` (that side's chunks from an ALREADY-run :func:`replay_battle`) skips the internal
    replay — a caller that already replayed the battle (e.g. for the other side's obs) passes them so
    the whole game is replayed through the driver ONCE, not once per side. ``impl`` selects that
    driver (``"node"`` default | ``"rust"``) and is ignored when ``chunks`` is supplied."""
    player = _run_inverting_replay(
        record, side, who="infer_action_indices", mappings=mappings,
        stop_after_decision=stop_after_decision, chunks=chunks, impl=impl, encode=False)
    return list(player.inverted_actions)


@dataclass(frozen=True)
class RecordDecision:
    """One decision of a battle read back from its reconstruction record ALONE.

    The forensic path (``states.npz``) has the obs and the action indices already; a TRAINING
    record has neither — the deleted ``--cf-records`` tap wrote only the seed, the teams
    and the committed choice strings. So everything here is recovered by replay: ``obs`` from the
    one-sided protocol, ``action`` by inverting ``choice`` through the real action mapper.

    ``choice`` is the sim-choice STRING the side actually committed at this decision — what a
    counterfactual feeds back to the sim to replay "the action that was really taken".
    """

    index: int                       # position in the side's decision sequence
    turn: int
    action: int                      # the action INDEX (inverted through the real mapper)
    choice: str                      # the recorded sim-choice string, e.g. "move icebeam"
    mask: np.ndarray
    obs: Optional[np.ndarray] = None
    # `gen3_cf_q_labels_v1`, only under ``scan_record(capture_choices=True)``: EVERY legal action
    # index at this decision → the sim-choice string the real mapper emits for it. ``choice`` is
    # the one entry the recorded policy took; this is the whole row, which is what a per-action
    # counterfactual sweep substitutes. ``None`` when the caller did not ask — an empty dict would
    # be indistinguishable from "asked, and nothing was legal".
    choices: Optional[dict] = None


def scan_record(
    record: ReconstructionRecord,
    side: Optional[str] = None,
    *,
    mappings=None,
    stall_config: Optional[StallConfig] = None,
    chunks: "Optional[Sequence[str]]" = None,
    impl: str = "node",
    encode: bool = True,
    capture_choices: bool = False,
) -> "list[RecordDecision]":
    """Every decision ``side`` made in ``record``, with its obs, mask, action index and choice string.

    The entry point a consumer of the TRAINING record tap needs: a ring record carries no
    ``states.npz`` and no recorded actions, so the only way to reach a training decision's
    observation is to replay the one-sided protocol and invert the committed choices. One replay
    yields all four facts.

    ``side`` defaults to the record's ``trainee_username``'s side when the record names one, and to
    ``"p1"`` otherwise — which is what a training record is, since ``BridgeSession`` always seats
    ``env.agent1`` (the trainee) on p1. ``chunks`` skips the internal :func:`replay_battle` when the
    caller has already run one. ``encode=False`` returns masks/actions/choices with ``obs=None``
    (cheap: it skips the ~80%-of-cost obs encode at every decision).

    ``capture_choices=True`` additionally fills each row's ``.choices`` with the FULL legal action
    → sim-choice-string map at that decision (`gen3_cf_q_labels_v1`). That is what a per-action
    counterfactual sweep substitutes, and asking for it here — inside the ONE replay this function
    already runs — is what keeps `cf_producer`'s q-sweep from paying a `materialize_from_record`
    prefix replay per labelled decision. It costs ~n_legal extra pure mapper calls per decision and
    is OFF by default, so every existing caller is byte-identical.
    """
    if side is None:
        side = (record.side_of(record.trainee_username) if record.trainee_username else "p1")
    player = _run_inverting_replay(
        record, side, who="scan_record", mappings=mappings, stall_config=stall_config,
        chunks=chunks, impl=impl, encode=encode, capture_choices=capture_choices)
    maps = player.decision_choices if capture_choices else []
    return [
        RecordDecision(index=i, turn=int(d.turn), action=int(a), choice=str(c),
                       mask=np.asarray(d.mask), obs=d.obs,
                       choices=(maps[i] if i < len(maps) else None))
        for i, (d, a, c) in enumerate(
            zip(player._materialized, player.inverted_actions, player.accepted_choices))
    ]


def materialize_from_record(
    record: ReconstructionRecord,
    *,
    username: Optional[str] = None,
    actions: Sequence[int] = (),
    mappings=None,
    stall_config: Optional[StallConfig] = None,
    map_actions_at: Optional[int] = None,
    stop_after_decision: Optional[int] = None,
    impl: str = "node",
) -> MaterializedTrace:
    """Convenience: replay the full recorded battle and materialize ``username``'s
    one-sided obs at every decision. ``username`` defaults to the record's
    ``trainee_username``. Only the regenerated per-side chunks cross into the
    obs pipeline — never the omniscient record fields. ``impl`` selects the replay driver
    (``"node"`` default | ``"rust"``)."""
    name = username or record.trainee_username
    if not name:
        raise ValueError("record carries no trainee_username — pass username=")
    side = record.side_of(name)
    rep = replay_battle(record, impl=impl)
    chunks = rep.p1_chunks if side == "p1" else rep.p2_chunks
    return materialize_decisions(
        chunks,
        username=name,
        packed_team=record.packed_team(side),
        side=side,
        actions=actions,
        battle_format=record.format_id,
        battle_tag=record.battle_tag,
        mappings=mappings,
        stall_config=stall_config,
        map_actions_at=map_actions_at,
        stop_after_decision=stop_after_decision,
    )
