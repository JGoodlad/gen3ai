"""The X50 census readout: summed shard counters -> `results/census.json` + `results/census.md`.

Called by `census.py aggregate`. Pure arithmetic over the counters `census.py` wrote; no corpus access.
"""
from __future__ import annotations

import collections
import json
from pathlib import Path
from typing import Any, Dict, List

BANDS = ["<1300", "1300-1499", "1500+", "1700+", "unrated", "all"]
TIER_A_FLOOR = 50_000          # ai_v11's pre-registered floor: >= 50k admitted tier-A decisions at >= 1500
# Hidden Power (`MOVE_hp`) is NOT a usable label: training resolves it to the TYPED num from the truth team, and a
# replay never states the type. It is reported in its own column.
LABEL_CHOICE = ["MOVE_rev", "MOVE_new", "SWITCH_rev", "SWITCH_new", "CANT_NAMED"]
LABEL_PROD = ["MOVE_rev", "MOVE_new", "MOVE_locked", "SWITCH_rev", "SWITCH_new"]


def pct(a: float, b: float) -> str:
    return f"{100.0 * a / b:.2f} %" if b else "-"


def _sub(C: collections.Counter, band: str, prefix: str) -> Dict[str, int]:
    head = f"{band}|{prefix}|"
    return {k[len(head):]: v for k, v in C.items() if k.startswith(head)}


def report(C: collections.Counter, meta: Dict[str, Any], out: Path) -> int:
    out.mkdir(parents=True, exist_ok=True)
    g = lambda band, key: C.get(f"{band}|{key}", 0)  # noqa: E731
    derived: Dict[str, Any] = {"bands": {}}
    md: List[str] = []
    md.append("# X50 S0 census -- results (generated by `census.py aggregate`; do not hand-edit)\n")
    md.append(f"Shards: {len(meta['dates'])} date folders ({meta['dates'][0] if meta['dates'] else '-'} .. "
              f"{meta['dates'][-1] if meta['dates'] else '-'}), {meta['files']:,} replays, "
              f"{meta['seconds'] / 3600:.2f} worker-pool hours. Binaries: {meta['bins']}.\n")

    # ---- 1. the reader
    md.append("## 1. The Rust reader on the corpus\n")
    md.append("| quantity | count |\n|---|---|")
    for k in ("replays", "reader|seats_read", "reader|refusal", "reader|refusal_classified", "reader|probes",
              "reader|probe_failure", "reader|present_fail", "replays_unfinished"):
        md.append(f"| `{k}` | {g('all', k):,} |")
    for k, v in sorted(_sub(C, "all", "anomaly").items()):
        md.append(f"| text-timeline anomaly `{k}` | {v:,} |")
    for k, v in sorted(_sub(C, "all", "check").items()):
        md.append(f"| text-vs-reader check `{k}` | {v:,} |")
    md.append("")
    if meta["examples"]:
        md.append("First example of each failure class: `census.json` -> `examples`.\n")

    # ---- 2. sides by band
    md.append("## 2. Sides (player-games) by rating band\n")
    md.append("| band | sides | full team revealed by game end | won / lost / no result |\n|---|---|---|---|")
    for b in BANDS:
        s = g(b, "sides")
        md.append(f"| {b} | {s:,} | {g(b, 'sides_full'):,} ({pct(g(b, 'sides_full'), s)}) | "
                  f"{g(b, 'sides|won'):,} / {g(b, 'sides|lost'):,} / {g(b, 'sides|nores'):,} |")
    md.append("")

    # ---- 3. the BC census
    md.append("## 3. Decisions of the ACTING side, by what its set shows BY GAME END (band = acting side's rating)\n")
    md.append("Decisions = one per side per turn (`td`) + forced replacements / Baton Pass targets (`fd`). "
              "Columns are NESTED left to right: full = all of the side's mons revealed; +act4 = and the acting "
              "mon showed 4 moves (ai_v11's tier A); +all4 = and every mon showed 4 moves; +items; +abilities. "
              "EVs / IVs / nature are never in a replay (0 % by construction).\n")
    md.append("| band | decisions (td + fd) | full | +act4 (tier A) | +all4 | +all items | +all abilities |"
              "\n|---|---|---|---|---|---|---|")
    for b in BANDS:
        d = g(b, "dec")
        row = [f"{d:,} ({g(b, 'dec|td'):,} + {d - g(b, 'dec|td'):,})"]
        for k in ("full", "full_act4", "full_all4", "full_all4_items", "full_all4_items_abil"):
            row.append(f"{g(b, k):,} ({pct(g(b, k), d)})")
        md.append(f"| {b} | " + " | ".join(row) + " |")
        derived["bands"][b] = {"decisions": d, "td": g(b, "dec|td"), "full": g(b, "full"),
                               "tier_a": g(b, "full_act4"), "full_all4": g(b, "full_all4"),
                               "full_all4_items": g(b, "full_all4_items"),
                               "full_all4_items_abil": g(b, "full_all4_items_abil"),
                               "tier_a_hazard_clean": g(b, "full_act4_hazclean")}
    md.append("")
    md.append("Marginals on the acting mon alone (not nested):\n")
    md.append("| band | acting mon 4 moves | acting mon item | acting mon ability |\n|---|---|---|---|")
    for b in BANDS:
        d = g(b, "dec")
        md.append(f"| {b} | {pct(g(b, 'act4'), d)} | {pct(g(b, 'act_item'), d)} | {pct(g(b, 'act_abil'), d)} |")
    md.append("")
    md.append("Per own mon revealed (per side, at game end):\n")
    md.append("| band | mons | 0 / 1 / 2 / 3 / 4 moves | item known | ability known (any route) | mons of a "
              "one-ability species (known from the species) | ability known on a two-ability species | ability by a protocol line (the "
              "reader's `ability_public`) |\n|---|---|---|---|---|---|---|---|")
    for b in BANDS:
        m = g(b, "mons")
        mv = " / ".join(pct(g(b, f"mon_moves|{k}"), m) for k in range(5))
        md.append(f"| {b} | {m:,} | {mv} | {pct(g(b, 'mon_item_known'), m)} | {pct(g(b, 'mon_abil_known'), m)} | "
                  f"{pct(g(b, 'mon_abil_single'), m)} | {pct(g(b, 'mon_abil_known_multi'), m)} | "
                  f"{pct(g(b, 'mon_abil_public'), m)} |")
    md.append("")
    md.append("Own mons revealed per side (share of sides):\n")
    md.append("| band | 1 | 2 | 3 | 4 | 5 | 6 |\n|---|---|---|---|---|---|---|")
    for b in BANDS:
        s = g(b, "sides") - g(b, "sides_no_view")
        md.append(f"| {b} | " + " | ".join(pct(g(b, f"mons_revealed|{k}"), s) for k in range(1, 7)) + " |")
    md.append("")

    # ---- 4. selection bias
    md.append("## 4. Selection bias: tier-A share by the acting side's result\n")
    md.append("| band | tier-A share, sides that WON | tier-A share, sides that LOST | ratio |\n|---|---|---|---|")
    for b in BANDS:
        w = g(b, "full_act4|won") / g(b, "dec|won") if g(b, "dec|won") else 0.0
        lo = g(b, "full_act4|lost") / g(b, "dec|lost") if g(b, "dec|lost") else 0.0
        md.append(f"| {b} | {100 * w:.2f} % | {100 * lo:.2f} % | {lo / w if w else 0:.2f} |")
    md.append("")

    # ---- 5. mask hazard
    md.append("## 5. Per-DECISION mask-hazard proxy (turn decisions; ai_v11 P0.4)\n")
    md.append("A turn decision where the replay's synthesised legal set would be over-permissive: trapped (ability "
              "/ Mean Look family / partial trap / Ingrain), Taunt / Encore / Disable / Torment active, a locked "
              "turn (recharge, charge, rampage), or a Choice Band holder (known by game end) that already moved. "
              "Undercounts: 0-PP and unrevealed Choice Bands are invisible.\n")
    flags = ["trap_ability", "trapped", "partial", "ingrain", "taunt", "encore", "disable", "torment", "locked",
             "choice"]
    md.append("| band | turn decisions | any hazard | " + " | ".join(flags) + " | tier A AND hazard-clean |\n|"
              + "---|" * (len(flags) + 4))
    for b in BANDS:
        t = g(b, "dec|td")
        md.append(f"| {b} | {t:,} | {pct(g(b, 'haz|any'), t)} | " + " | ".join(pct(g(b, f'haz|{f}'), t) for f in flags)
                  + f" | {g(b, 'full_act4_hazclean'):,} |")
    md.append("")

    # ---- 6. the intent labels
    md.append("## 6. Opponent-intent labels (band = the LABELLED human's rating)\n")
    md.append("Every turn decision of the viewer gets the opponent's action that turn as its label. CHOICE = the "
              "opponent's observable turn choice; PROD = the production label rules approximated on the text "
              "(a window closing on the viewer's forced switch, a phaze / faint / Baton Pass co-occurring with a "
              "switch, or an Encore override all MASK). `_rev` = the move / switch-in was already revealed before "
              "the decision (alpha's seat / beta's slot exists deterministically); `_new` = first reveal (the "
              "belief must have put it in its top-K seats, unmeasured here); `MOVE_hp` = Hidden Power (the "
              "replay never states its type).\n")
    for sem, lab in (("choice", LABEL_CHOICE), ("prod", LABEL_PROD)):
        md.append(f"### {sem.upper()}\n")
        cats = sorted(set().union(*[_sub(C, b, f"int|{sem}").keys() for b in BANDS]))
        md.append("| band | viewer turn decisions | LABELLED | labelled & already revealed | " + " | ".join(cats)
                  + " |\n|" + "---|" * (len(cats) + 4))
        derived[f"intent_{sem}"] = {}
        for b in BANDS:
            t = g(b, "int|td")
            sub = _sub(C, b, f"int|{sem}")
            labelled = sum(sub.get(c, 0) for c in lab)
            rev = sum(sub.get(c, 0) for c in lab if c.endswith("_rev"))
            derived[f"intent_{sem}"][b] = {"td": t, "labelled": labelled, "labelled_revealed": rev, **sub}
            md.append(f"| {b} | {t:,} | {labelled:,} ({pct(labelled, t)}) | {rev:,} ({pct(rev, t)}) | "
                      + " | ".join(pct(sub.get(c, 0), t) for c in cats) + " |")
        md.append("")

    # ---- 7. the feasibility line
    ta = g("1500+", "full_act4")
    tac = g("1500+", "full_act4_hazclean")
    md.append("## 7. Against ai_v11's floor (>= 50k admitted tier-A decisions at >= 1500)\n")
    md.append(f"Tier A at 1500+: **{ta:,}** ({'CLEARS' if ta >= TIER_A_FLOOR else 'BELOW'} the floor); tier A AND "
              f"hazard-clean: **{tac:,}** ({'CLEARS' if tac >= TIER_A_FLOOR else 'BELOW'}). Stricter: full team + "
              f"every mon 4 moves at 1500+: {g('1500+', 'full_all4'):,}; + every item: "
              f"{g('1500+', 'full_all4_items'):,}.\n")
    derived["floor"] = {"tier_a_1500": ta, "tier_a_hazclean_1500": tac, "floor": TIER_A_FLOOR}
    hist = {int(k.split("|")[1]): v for k, v in C.items() if k.startswith("hist|")}
    derived["rating_hist_50"] = dict(sorted(hist.items()))
    (out / "census.json").write_text(json.dumps({"meta": {k: v for k, v in meta.items()}, "derived": derived,
                                                 "counters": dict(sorted(C.items()))}, indent=1, default=str) + "\n")
    (out / "census.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))
    return 0
